-- Description affichée sur la fiche d'une caisse
ALTER TABLE cases ADD COLUMN description TEXT;

-- drop_weight est exprimé en millièmes de pourcent :
-- 100 000 = 100 %, 1 000 = 1 %, 250 = 0,25 %.
-- Le moteur de tirage tire un ticket entre 0 et 99 999 : une caisse n'est
-- ouvrable que si la somme de ses drop_weight vaut exactement 100 000.
COMMENT ON COLUMN case_items.drop_weight IS
    'Probabilité en millièmes de pourcent (100000 = 100 %). Somme par caisse = 100000.';

